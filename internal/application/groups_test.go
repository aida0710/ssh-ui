// groupFixture は、parent フィールド版が記述していたのと同じ階層を、
// ファイルシステムの言い方で述べる: "work" が "company" の中にネストしているのは
// そのディレクトリがそうだからであり、各 host はそのファイルが置かれたグループに属す。
func groupFixture() ([]string, Metadata, []HostEntry) {
	metadata := NewMetadata()
	metadata.Groups = []GroupMetadata{
		{Name: "company", Settings: []Setting{{Keyword: "ServerAliveInterval", Values: []string{"30"}}}},
		{Name: "company/work", Settings: []Setting{
			{Keyword: "User", Values: []string{"ops"}},
			{Keyword: "Port", Values: []string{"2222"}},
		}},
	}
	hosts := []HostEntry{
		{Identity: HostIdentity{Path: "connections/company/work/build.conf", Alias: "build01"}, Group: "company/work"},
		{Identity: HostIdentity{Path: "connections/company/web.conf", Alias: "web01"}, Group: "company"},
	}
	return []string{"company/work", "company"}, metadata, hosts
}

func TestCompileGroupsPutsChildrenBeforeParentsAndInheritsMembers(t *testing.T) {
	declared, metadata, hosts := groupFixture()

	contents, notices := CompileGroups(declared, metadata, hosts, "\n")
	const want = `# Generated by sshc from ~/.ssh/sshc/metadata.json.
# Child groups come first because OpenSSH keeps the first value it reads.
# Edit groups in the UI; hand edits to this file are replaced on the next save.

# group company/work (parent company)
Host build01
	User ops
	Port 2222

# group company
Host build01 web01
	ServerAliveInterval 30
`
	if got := string(contents); got != want {
		t.Fatalf("contents =\n%q\nwant\n%q", got, want)
	}
	// 射影に無いメンバーはもはや notice ではない: ディスク上の
	// ファイルと食い違いうる 2 つ目のメンバー一覧は存在しないからだ。
	if len(notices) != 0 {
		t.Fatalf("notices = %#v", notices)
	}
}

func TestCompileGroupsRendersParsableLosslessConfiguration(t *testing.T) {
	declared, metadata, hosts := groupFixture()
	contents, _ := CompileGroups(declared, metadata, hosts, "\n")
	parsed := config.Parse(contents)
	if string(parsed.Render()) != string(contents) {
		t.Fatal("generated group configuration does not round-trip")
	}
	for index, line := range parsed.Lines {
		if line.Kind == config.LineUnstructured {
			t.Fatalf("generated line %d is unstructured: %q", index+1, line.Text)
		}
	}
}

// グループ名はディレクトリパスなので、階層は循環を含み得ない:
// 循環が排除されていることを証明していたテストは、循環が
// そもそも表現不能であることを証明するテストに置き換えられた。
func TestAGroupCanNeverBeItsOwnAncestor(t *testing.T) {
	for _, name := range []string{"a/b/c", "work", "a/b/a"} {
		seen := map[string]bool{}
		for current := name; current != ""; current = ParentGroupName(current) {
			if seen[current] {
				t.Fatalf("%q reaches %q twice", name, current)
			}
			seen[current] = true
		}
	}
}

func regionFile(t *testing.T, groups ...string) *config.File {
	t.Helper()
	file := config.Parse(nil)
	plan, err := PlanRegion(file, groups, DefaultGroupsFile)
	if err != nil {
		t.Fatalf("PlanRegion error = %v", err)
	}
	if err := ApplyRegion(file, plan); err != nil {
		t.Fatalf("ApplyRegion error = %v", err)
	}
	return file
}

func TestDeclaredGroupsReadsTheRegionAndNothingElse(t *testing.T) {
	file := regionFile(t, "work/eu", "work", "home")
	declared := DeclaredGroups(file)
	want := []string{"work/eu", "work", "home"}
	if len(declared) != len(want) {
		t.Fatalf("declared = %#v", declared)
	}
	for index := range want {
		if declared[index] != want[index] {
			t.Fatalf("declared = %#v, want %#v", declared, want)
		}
	}

	// マーカーの外にユーザー自身が書いた Include は何も宣言しない:
	// 宣言なのは region であって、たまたまディレクトリを名指しする
	// すべての行ではない。
	handWritten := config.Parse([]byte("Include connections/marketing/*.conf\n"))
	if got := DeclaredGroups(handWritten); len(got) != 0 {
		t.Errorf("DeclaredGroups outside the region = %#v, want none", got)
	}
}

func TestBuildGroupsViewReportsADirectoryThatWasNeverDeclared(t *testing.T) {
	// ~/.ssh/connections/marketing は存在するが、どの行もそれを
	// 名指ししない。それを採用するとしたら、このアプリケーションが
	// 他人のディレクトリを自分のグループの 1 つだと決めつけることになる。
	views, notices := BuildGroupsView(regionFile(t, "work"), nil, NewMetadata(), []string{"work", "marketing"})

	if len(views) != 1 || views[0].Name != "work" {
		t.Fatalf("views = %#v, want only the declared group", views)
	}
	if !hasNotice(notices, NoticeGroupNotDeclared, "marketing") {
		t.Errorf("notices = %#v, want group_not_declared for marketing", notices)
	}
}

