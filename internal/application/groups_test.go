func TestBuildGroupsViewCarriesTheDirectoriesAndTheHierarchy(t *testing.T) {
	metadata := NewMetadata()
	metadata.Groups = []GroupMetadata{{Name: "work/eu", Colour: "#f97316"}}
	hosts := []HostEntry{
		{Identity: HostIdentity{Path: "connections/work/eu/lon.conf", Alias: "lon-1"}, Group: "work/eu"},
	}
	views, _ := BuildGroupsView(regionFile(t, "work/eu", "work"), hosts, metadata, []string{"work", "work/eu"})

	if len(views) != 2 || views[0].Name != "work/eu" {
		t.Fatalf("views = %#v, want the child first", views)
	}
	child := views[0]
	if child.Parent != "work" || child.Directory != "connections/work/eu" || child.KeyDirectory != "keys/work/eu" {
		t.Errorf("child = %#v", child)
	}
	if child.MemberCount != 1 || child.Colour != "#f97316" {
		t.Errorf("child = %#v", child)
	}
}

func hasNotice(notices []Notice, code, detail string) bool {
	for _, notice := range notices {
		if notice.Code == code && notice.Detail == detail {
			return true
		}
	}
	return false
}

// 3 つのグループ診断は、グループを表示する画面に届く。
//
// それらは計算され、テストされていたが、何にも提供されていなかった: どの
// Include も名指ししない connections/ 配下のディレクトリ、ディレクトリが消えた
// 宣言済みグループ、中身のない宣言済みグループは、すべて見えなかった。それぞれは
// 誰かが対処すべき状態であり、最初のものは黙って何もしないという状態である。
func TestTheOverviewCarriesTheGroupDiagnostics(t *testing.T) {
	service, workspace := newTestService(t)
	declareGroup(t, service, "work", "archive")
	writeGroupFile(t, workspace, "work", "web.conf", "Host web-1\n\tHostName 203.0.113.10\n")
	// archive は宣言されており、そのディレクトリは何も保持していない。
	// scratch は何にも宣言されていないディレクトリである。
	if err := os.MkdirAll(filepath.Join(workspace.Root(), "connections", "scratch"), 0o700); err != nil {
		t.Fatal(err)
	}
	// gone は宣言されているが、そのディレクトリは存在しない。
	declareGroup(t, service, "work", "archive", "gone")
	if err := os.RemoveAll(filepath.Join(workspace.Root(), "connections", "gone")); err != nil {
		t.Fatal(err)
	}

	overview, err := service.Overview()
	if err != nil {
		t.Fatalf("Overview = %v", err)
	}
	for _, want := range []struct{ code, detail string }{
		{NoticeGroupNotDeclared, "scratch"},
		{NoticeGroupEmpty, "archive"},
		{NoticeGroupDirectoryMissing, "gone"},
	} {
		if !hasNotice(overview.Notices, want.code, want.detail) {
			t.Errorf("notices = %#v, want %s for %s", overview.Notices, want.code, want.detail)
		}
	}
	// そしてグループ自体も、それぞれが保持するものと共に運ばれる。
	byName := map[string]GroupView{}
	for _, group := range overview.Groups {
		byName[group.Name] = group
	}
	if got := byName["work"]; got.MemberCount != 1 || !got.DirectoryPresent {
		t.Errorf("work = %#v, want one member and a directory", got)
	}
	if got := byName["gone"]; got.DirectoryPresent {
		t.Errorf("gone reports a directory it does not have: %#v", got)
	}
}

// マーカーが 1 つしかない region は壊れた region であり、
// 4 つのディレクトリが「宣言されていない」と言うのは実際に起きたこととは違う。
//
// Include 行は存在し、OpenSSH はそれを読む。欠けているのは
// 終端マーカーであり、このアプリケーションは自分が生成した行が
// どこで終わるか分からなくなる — そのためすべてのグループが未宣言に
// 見えてしまった。4 つの誤解を招く notice が、1 つの真実の notice に置き換えられた。
func TestADamagedRegionIsReportedAsItselfRatherThanAsUndeclaredGroups(t *testing.T) {
	service, workspace := newTestService(t)
	declareGroup(t, service, "work")
	writeGroupFile(t, workspace, "work", "web.conf", "Host web-1\n")

	// 終端マーカーを取り除く。それは手動編集が残す状態である。
	entry := readFile(t, workspace, "config")
	damaged := strings.ReplaceAll(entry, RegionEndMarker+"\n", "")
	if damaged == entry {
		t.Fatalf("the fixture has no end marker to remove: %q", entry)
	}
	if err := os.WriteFile(filepath.Join(workspace.Root(), "config"), []byte(damaged), 0o600); err != nil {
		t.Fatal(err)
	}

	overview, err := service.Overview()
	if err != nil {
		t.Fatalf("Overview = %v", err)
	}
	if !hasNotice(overview.Notices, NoticeRegionDamaged, "") {
		t.Errorf("notices = %#v, want %s", overview.Notices, NoticeRegionDamaged)
	}
	for _, notice := range overview.Notices {
		if notice.Code == NoticeGroupNotDeclared {
			t.Errorf("a damaged region was reported as an undeclared group: %#v", notice)
		}
	}
}
